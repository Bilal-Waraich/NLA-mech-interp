"""Generate and push a Kaggle run ``kaggle_runs/<slug>/`` that calls one repository script (build spec
section 6). The run unpacks the code from ``medinterp-src``, finds the inputs it was told to look for under
``/kaggle/input`` by file name, runs the script with its outputs in ``/kaggle/working``, and nothing else.
Every run is private; ``--account`` picks the project account that owns it (default: the first configured
account, see ``kaggle_sync.project_accounts``).

Placeholders in the script arguments: ``{working}`` = /kaggle/working, ``{find:NAME}`` = the directory
under /kaggle/input that contains a file or folder NAME.

Run:  ~/.venvs/nla-mech-interp/bin/python scripts/kaggle_push.py bench-cpu --script scripts/benchmark_sae.py \
          --args "--device cpu --label kaggle_cpu --out {working}" [--gpu]
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kaggle_sync import kaggle_env, project_accounts  # noqa: E402  (sibling script: accounts and tokens)

REPO = Path(__file__).resolve().parents[1]
KAGGLE = Path.home() / ".venvs/kaggle-cli/bin/kaggle"

RUN_PY = '''"""Generated by scripts/kaggle_push.py; do not edit."""
import os, re, subprocess, sys, tarfile, time
from pathlib import Path

SCRIPT = {script!r}
ARGS = {args!r}
INPUT, WORKING, CODE = Path("/kaggle/input"), Path("/kaggle/working"), Path("/tmp/medinterp")


def find(name):
    hits = sorted(p.parent for p in INPUT.rglob(name))
    if not hits:
        sys.exit(f"{{name}} not found under {{INPUT}}")
    return str(hits[0])


archive = next(INPUT.rglob("medinterp_src.tar.gz"), None)
if archive is not None:
    CODE.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive) as t:
        t.extractall(CODE)
else:  # Kaggle may have unpacked the archive itself
    CODE = Path(find("pyproject.toml"))
args = [a.replace("{{working}}", str(WORKING)) for a in ARGS]
args = [re.sub(r"\\{{find:([^}}]+)\\}}", lambda m: find(m.group(1)), a) for a in args]
t0 = time.time()
code = subprocess.call([sys.executable, str(CODE / SCRIPT), *args],
                       env={{**os.environ, "MEDINTERP_DATA": str(WORKING)}})
print(f"elapsed {{(time.time() - t0) / 3600:.3f}} h, exit {{code}}", flush=True)
sys.exit(code)
'''


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("slug")
    ap.add_argument("--script", required=True, help="repository-relative path of the script to run")
    ap.add_argument("--args", default="", help="arguments of the script (one string, split on spaces)")
    ap.add_argument("--gpu", action="store_true", help="T4 x2; default is a CPU run")
    ap.add_argument("--dataset", action="append", default=[], help="extra private dataset slug of the same account")
    ap.add_argument("--kernel-source", action="append", default=[], help="earlier run (slug, same account) whose output is an input")
    accounts = project_accounts()
    ap.add_argument("--account", choices=accounts, default=accounts[0])
    ap.add_argument("--no-push", action="store_true", help="only write the folder")
    a = ap.parse_args()

    folder = REPO / "kaggle_runs" / a.slug
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "run.py").write_text(RUN_PY.format(script=a.script, args=a.args.split()))
    meta = {"id": f"{a.account}/{a.slug}", "title": a.slug, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": "true", "enable_gpu": "true" if a.gpu else "false",
            "enable_internet": "true",
            "dataset_sources": [f"{a.account}/medinterp-src", *(f"{a.account}/{d}" for d in a.dataset)],
            "competition_sources": [], "kernel_sources": [f"{a.account}/{k}" for k in a.kernel_source], "model_sources": []}
    (folder / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    if a.no_push:
        print(f"wrote {folder}")
        return
    cmd = [str(KAGGLE), "kernels", "push", "-p", str(folder)]
    if a.gpu:
        cmd += ["--accelerator", "NvidiaTeslaT4"]
    subprocess.run(cmd, check=True, env=kaggle_env(a.account))
    # Every pushed run gets its row in results/run_index.csv at once (status is filled on the next full refresh).
    subprocess.run([sys.executable, str(REPO / "scripts/run_index.py"), "--no-status"], check=False)


if __name__ == "__main__":
    main()
